def run(cmd, dry):
    print("  $ " + " ".join(cmd))
    if dry:
        return 0
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        print(f"    !! rc={r.returncode} {r.stderr.strip()}")
    return r.returncode


def mv(old, new, use_git, dry):
    if not os.path.isdir(old):
        print(f"  -- skip (missing): {old}")
        return
    if os.path.exists(new):
        print(f"  !! target exists, skip: {new}")
        return
    if use_git:
        rc = run(["git", "mv", old, new], dry)
        if rc != 0:
            print("    fallback to plain mv")
            run(["mv", old, new], dry)
    else:
        run(["mv", old, new], dry)


def main():
    dry = "--dry-run" in sys.argv
    reverse = "--reverse" in sys.argv

    if reverse:
        # 回滚：根先复原，再复原二级
        print("== reverse: roots ==")
        for old, new in ROOT_MAP.items():
            mv(new, old, old not in PLAIN_MV_ROOTS, dry)
        print("== reverse: L2 ==")
        for parent, pairs in L2_MAP.items():
            for c_old, c_new in pairs:
                mv(os.path.join(parent, c_new), os.path.join(parent, c_old), True, dry)
        return 0

    # 正向：先二级（在旧根路径下），后根
    print("== phase 1: L2 renames ==")
    for parent, pairs in L2_MAP.items():
        for c_old, c_new in pairs:
            mv(os.path.join(parent, c_old), os.path.join(parent, c_new), True, dry)

    print("== phase 2: root renames ==")
    for old, new in ROOT_MAP.items():
        mv(old, new, old not in PLAIN_MV_ROOTS, dry)
    return 0


if __name__ == "__main__":
    sys.exit(main())
